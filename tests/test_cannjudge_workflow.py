def review(source=SOURCE):
    return {'kernel_sha256': digest(source), 'reviewer': 'local-fixture-only',
            'reviewed_at': '2026-10-15', 'device_math_notes': 'Fixture, not a real source review.',
            'assertions': {r: True for r in RULES}}


def fixture_candidate(directory):
    evidence = directory / 'evidence'
    evidence.mkdir(parents=True)
    case = {'name': 'fixture', 'passed': True, 'guard_ok': True, 'zero_identity_ok': True,
            'launch_audit': True, 'one_kernel_per_iteration': True, 'iterations': 2, 'kernel_launches': 2}
    normal = {'source_sha256': digest(SOURCE), 'binary_sha256': 'test-binary', 'cases': [case]}
    write_json(evidence / 'compliance.json', review())
    package = {'kernel_sha256': digest(SOURCE), 'git_commit': 'fixture', 'validated_case_count': 1,
               'single_kernel_per_iteration': True, 'template_diff': {'changed': ['kernel.asc']},
               'compliance_policy': 'device-computation-supplement-2026-10-15',
               'compliance_review_sha256': digest((evidence / 'compliance.json').read_bytes())}
    profile = {'source_sha256': digest(SOURCE), 'binary_sha256': 'test-binary',
               'single_kernel_rule_passed': True, 'run_kernel_calls': 75, 'actual_device_kernel_tasks': 75}
    for name, value in [('package.json', package), ('compliance.json', review()),
                        ('correctness.json', normal), ('launch_audit.json', normal), ('launch_count.json', profile)]:
        write_json(evidence / name, value)
    (directory / 'kernel.asc').write_bytes(SOURCE)
    manifest = {'kernel_sha256': digest(SOURCE), 'git_commit': 'fixture',
                'evidence_sha256': {p.name: digest(p.read_bytes()) for p in evidence.iterdir()}}
    write_json(directory / 'candidate.json', manifest)
    return manifest


class CoreTests(unittest.TestCase):
    def test_host_frequency_table_is_blocked(self):
        source = SOURCE.replace(b'launch_device(theta)', b'frequencies.value[i]=1.0f/std::pow(theta, exponent)')
        report = static_audit(source)
        self.assertFalse(report['static_screen_passed'])
        self.assertIn('host_math', {i['rule'] for i in report['issues']})

    def test_math_in_comments_is_ignored_but_actual_math_is_not(self):
        source = SOURCE.replace(b'launch_device(theta)', b'/* std::pow(theta, 2) */ launch_device(theta)')
        self.assertTrue(static_audit(source)['static_screen_passed'])
        self.assertFalse(static_audit(source.replace(b'launch_device(theta)', b'std::pow(theta, 2)'))['static_screen_passed'])

    def test_old_or_missing_review_is_blocked(self):
        check_review(SOURCE, review())
        with self.assertRaises(ValueError):
            check_review(SOURCE + b'\n', review())
        r = review(); r['assertions'][RULES[0]] = False
        with self.assertRaises(ValueError):
            check_review(SOURCE, r)

    def test_candidate_and_evidence_tampering(self):
        with tempfile.TemporaryDirectory() as temporary:
            directory = Path(temporary)
            fixture_candidate(directory)
            validate_candidate(directory)
            (directory / 'evidence/correctness.json').write_text('{}')
            with self.assertRaises(ValueError):
                validate_candidate(directory)

    def test_candidate_truncation(self):
        with tempfile.TemporaryDirectory() as temporary:
            directory = Path(temporary); fixture_candidate(directory)
            (directory / 'kernel.asc').write_bytes(SOURCE[30:])
            with self.assertRaises(ValueError):
                validate_candidate(directory)

    def test_extra_kernel_launches_are_blocked(self):
        with tempfile.TemporaryDirectory() as temporary:
            directory = Path(temporary); manifest = fixture_candidate(directory)
            path = directory / 'evidence/launch_count.json'
            report = read_json(path); report['actual_device_kernel_tasks'] = 85
            write_json(path, report)
            manifest['evidence_sha256']['launch_count.json'] = digest(path.read_bytes())
            write_json(directory / 'candidate.json', manifest)
            with self.assertRaises(ValueError): validate_candidate(directory)

    def test_crash_and_duplicate_prevention(self):
        with tempfile.TemporaryDirectory() as temporary:
            journal = Journal(temporary)
            candidate = {'kernel_sha256': 'abc', 'git_commit': 'fixture'}
            record = journal.create(candidate, {'submit_url': 'fixture'})
            with self.assertRaises(ValueError):
                journal.create(dict(candidate, kernel_sha256='new'), {'submit_url': 'fixture'})
            record['state'] = 'accepted'; journal.save(record)
            with self.assertRaises(ValueError):
                journal.create(candidate, {'submit_url': 'fixture'})
            journal.create(dict(candidate, kernel_sha256='new'), {'submit_url': 'fixture'})

    def test_units(self):
        self.assertEqual(latency_us('3.37ms'), 3370)
        self.assertEqual(latency_us(' 2.5 μs '), 2.5)
        self.assertEqual(latency_us('2500 ns'), 2.5)
        for value in ('3.2', '0 us', 'nan us', '2 ms average', '-1 us'):
            with self.subTest(value=value), self.assertRaises(ValueError):
                latency_us(value)

    def test_origin(self):
        check_origin('https://cannjudge.cn/record/1', 'https://cannjudge.cn')
        for url in ('https://cannjudge.cn.evil.invalid/', 'http://cannjudge.cn/', 'https://user@cannjudge.cn/'):
            with self.subTest(url=url), self.assertRaises(ValueError):
                check_origin(url, 'https://cannjudge.cn')

    def test_timing_comparison_and_precision_gate(self):
        baseline = {'state': 'accepted', 'kernel_sha256': 'base',
                    'cases': [{'id': i, 'latency_us': i * 4} for i in range(1, 16)]}
        candidate = copy.deepcopy(baseline)
        for c in candidate['cases']: c['latency_us'] /= 2
        self.assertAlmostEqual(compare_results(baseline, candidate)['geometric_mean_speedup'], 2)
        candidate['state'] = 'rejected'
        with self.assertRaises(ValueError): compare_results(baseline, candidate)
        candidate['state'] = 'accepted'; candidate['cases'][0]['latency_us'] = 0
        with self.assertRaises(ValueError): compare_results(baseline, candidate)

    def test_uncalibrated_site_cannot_submit(self):
        config = read_json(ROOT / 'tools/judge_workflow/cannjudge.example.json')
        with self.assertRaises(ValueError): validate_config(config)


class Handler(BaseHTTPRequestHandler):
    posts = 0
    status = 'Accepted'

    def log_message(self, *_):
        pass

    def do_POST(self):
        type(self).posts += 1
        self.send_response(200); self.send_header('Content-Type', 'application/json'); self.end_headers()
        self.wfile.write(b'{"id":"job-1"}')

    def do_GET(self):
        self.send_response(200); self.send_header('Content-Type', 'text/html; charset=utf-8'); self.end_headers()
        if self.path == '/keyboard':
            self.wfile.write('''<a href="#logout">退出</a>
              <div class="tree is-file active" data-file="kernel.asc"></div>
              <div class="tree is-file active" data-file="kernel.asc"></div>
              <div class="tree is-file is-readonly" data-file="main.asc"></div>
              <div class="monaco-editor"><textarea>old kernel</textarea></div>
              <button id="copy" onclick="navigator.clipboard.writeText(document.querySelector('textarea').value)">copy</button>'''.encode())
        elif self.path == '/submit':
            self.wfile.write('''<button onclick="send()">提交代码</button><div id="links"></div>
            <script>
            const make=(uri,text)=>({uri:{toString:()=>uri},getValue:()=>text,setValue:t=>{text=t}});
            const models=[make('file:///project/kernel.asc','old kernel'),make('file:///project/main.asc','original main')];
            window.monaco={editor:{getModels:()=>models}};
            async function send(){const r=await fetch('/submit-job',{method:'POST'});const j=await r.json();
              document.querySelector('#links').innerHTML=`<a class="result" href="/results/${j.id}">result</a>`;}
            </script>'''.encode())
        else:
            rows = ''.join(f'<tr class="case"><td class="id">测试点 {i}</td><td class="latency">{i}.5 μs</td><td class="ok">PASS</td></tr>'
                           for i in range(1, 16))
            self.wfile.write(f'<div id="submission-id">job-1</div><div id="status">{self.status}</div><table>{rows}</table>'.encode())


class BrowserTests(unittest.IsolatedAsyncioTestCase):
    @classmethod
    def setUpClass(cls):
        cls.server = ThreadingHTTPServer(('127.0.0.1', 0), Handler)
        cls.thread = threading.Thread(target=cls.server.serve_forever, daemon=True); cls.thread.start()

    @classmethod
    def tearDownClass(cls):
        cls.server.shutdown(); cls.server.server_close(); cls.thread.join()

    async def asyncSetUp(self):
        from playwright.async_api import async_playwright
        self.playwright = await async_playwright().start()
        self.browser = await self.playwright.chromium.launch(headless=True, channel=os.environ.get('CANNJUDGE_TEST_CHANNEL'))
        self.context = await self.browser.new_context()
        self.page = await self.context.new_page()
        self.origin = f'http://127.0.0.1:{self.server.server_port}'
        self.config = read_json(ROOT / 'tools/judge_workflow/cannjudge.example.json')
        self.config.update(calibrated=True, submit_url=self.origin + '/submit', allowed_origin=self.origin,
                           result_link_selector='a.result', result_url_pattern=r'/results/job-\d+$',
                           result_id_selector='#submission-id', result_status_selector='#status',
                           case_row_selector='.case', case_id_selector='.id', case_latency_selector='.latency',
                           case_status_selector='.ok', poll_seconds=5, result_timeout_seconds=30)
        self.temporary = tempfile.TemporaryDirectory()
        self.journal = Journal(Path(self.temporary.name) / 'runs')
        Handler.posts = 0; Handler.status = 'Accepted'
        await self.page.goto(self.config['submit_url'])

    async def asyncTearDown(self):
        self.temporary.cleanup()
        await self.browser.close(); await self.playwright.stop()

    async def test_full_source_readback_and_other_file_unchanged(self):
        result = await replace_kernel(self.page, self.config, SOURCE)
        self.assertEqual(result['readback_sha256'], digest(SOURCE))
        models = await self.page.evaluate(MODELS)
        self.assertEqual(models[1]['text'], 'original main')

    async def test_cross_file_side_effect_is_blocked(self):
        await self.page.evaluate("monaco.editor.getModels()[0].setValue=t=>monaco.editor.getModels()[1].setValue(t)")
        with self.assertRaises(ValueError): await replace_kernel(self.page, self.config, SOURCE)
        self.assertEqual(Handler.posts, 0)

    async def test_complete_submission_and_fifteen_results(self):
        await replace_kernel(self.page, self.config, SOURCE)
        record = await click_once(self.context, self.page, self.config,
                                  {'kernel_sha256': digest(SOURCE), 'git_commit': 'fixture'}, self.journal)
        self.assertEqual(Handler.posts, 1)
        record = await poll_result(self.context, self.config, self.journal, record)
        self.assertEqual(record['state'], 'accepted')
        self.assertEqual(len(record['cases']), 15)
        self.assertEqual(record['submission_id'], 'job-1')
        with self.assertRaises(ValueError):
            await click_once(self.context, self.page, self.config,
                             {'kernel_sha256': digest(SOURCE), 'git_commit': 'fixture'}, self.journal)
        self.assertEqual(Handler.posts, 1)

