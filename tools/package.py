#!/usr/bin/env python3
"""Package the untouched original template with kernel.asc as the sole replacement."""
import argparse
import json
from pathlib import Path
import subprocess
from zipfile import ZIP_DEFLATED, ZipFile

from verify_submission import ROOT, original_template, sha256, verify


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--result', default='kernel_only')
    args = ap.parse_args()
    source = (ROOT/'operators/rotary_pos_emb/kernel.asc').read_bytes()
    digest = sha256(source)
    result = json.loads((ROOT/'benchmarks/results'/f'{args.result}.json').read_text())
    names = {c['name'] for c in json.loads((ROOT/'tests/cases.json').read_text())}
    if {c['name'] for c in result['cases']} != names:
        raise SystemExit('Packaging requires the complete correctness suite')
    if not all(c['passed'] and c['guard_ok'] and c.get('zero_identity_ok', False)
               for c in result['cases']):
        raise SystemExit('Correctness gate failed')
    if result['source_sha256'] != digest:
        raise SystemExit('Results do not belong to current source; rebuild and retest')
    revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    committed = subprocess.check_output(
        ['git', 'show', revision+':operators/rotary_pos_emb/kernel.asc'], cwd=ROOT)
    if sha256(committed) != digest:
        raise SystemExit('Commit the validated kernel before packaging')

    payload = original_template()
    payload['kernel.asc'] = source
    diff = verify(payload, source)
    dest = ROOT/'dist'
    dest.mkdir(exist_ok=True)
    directory = dest/'rotaryposemb_1743_submission'
    directory.mkdir(exist_ok=True)
    # Remove only the extra metadata file generated by the superseded packager.
    # Metadata belongs beside the archive, never inside the competition project.
    (directory/'manifest.json').unlink(missing_ok=True)
    existing = {p.relative_to(directory).as_posix() for p in directory.rglob('*') if p.is_file()}
    if existing-set(payload):
        raise SystemExit('Unexpected files in submission directory: '+str(sorted(existing-set(payload))))
    for name, data in payload.items():
        target = directory/name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    (dest/'kernel.asc').write_bytes(source)
    archive = dest/'rotaryposemb_1743_submission.zip'
    with ZipFile(archive, 'w', ZIP_DEFLATED) as z:
        z.writestr('scripts/', b'')
        for name, data in sorted(payload.items()):
            z.writestr(name, data)
    metadata = dict(problem=1743, git_commit=revision, kernel_sha256=digest,
                    result=args.result, validated_case_count=len(result['cases']),
                    template_diff=diff, platform_hidden_cases_tested=False)
    (dest/'manifest.json').write_text(json.dumps(metadata, indent=2)+'\n')
    print(json.dumps(dict(kernel=str(dest/'kernel.asc'), archive=str(archive),
                          directory=str(directory), **metadata), indent=2))


if __name__ == '__main__':
    main()
